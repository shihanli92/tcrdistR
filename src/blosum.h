// ---------------------------------------------------------------------------
// aa_to_index — constexpr char -> 0..19 (or -1 for invalid)
// ---------------------------------------------------------------------------
// Only the 20 amino acids in AA_ORDER map to valid indices.
// Positions in the 26-letter English alphabet that are not AAs return -1.

constexpr int aa_to_index(char c) {
    // AA_ORDER: A=0 C=1 D=2 E=3 F=4 G=5 H=6 I=7 K=8 L=9 M=10 N=11
    //           P=12 Q=13 R=14 S=15 T=16 V=17 W=18 Y=19
    // Letters not in AMINO_ACIDS: B J O U X Z
    switch (c) {
        case 'A': return  0;
        case 'C': return  1;
        case 'D': return  2;
        case 'E': return  3;
        case 'F': return  4;
        case 'G': return  5;
        case 'H': return  6;
        case 'I': return  7;
        case 'K': return  8;
        case 'L': return  9;
        case 'M': return 10;
        case 'N': return 11;
        case 'P': return 12;
        case 'Q': return 13;
        case 'R': return 14;
        case 'S': return 15;
        case 'T': return 16;
        case 'V': return 17;
        case 'W': return 18;
        case 'Y': return 19;
        default:  return -1;
    }
}

